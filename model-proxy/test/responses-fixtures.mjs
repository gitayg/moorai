// No fixture here is a recorded provider response; each is built from those types.
const sse = (d) => `event: ${d.type}\ndata: ${JSON.stringify(d)}\n\n`;

export const RESP_ID = "resp_fake01";
const base = (status, output) => ({ id: RESP_ID, object: "response", created_at: 1759700000, status, model: "gpt-fake", output, parallel_tool_calls: true, tool_choice: "auto", tools: [], usage: status === "completed" ? { input_tokens: 12, output_tokens: 9, total_tokens: 21 } : null });
const message = (text, status = "completed") => ({ type: "message", id: "msg_fake01", status, role: "assistant", content: text == null ? [] : [{ type: "output_text", text, annotations: [] }] });
const fcall = (t, i, args = JSON.stringify(t.input), status = "completed") => ({ type: "function_call", id: `fc_fake0${i}`, call_id: `call_fake0${i}`, name: t.name, arguments: args, status });

// A non-streaming Response: an optional text message, then one function_call per tool.
export function responsesBody({ text = "Sure.", tools = [] } = {}) {
  return base("completed", [...(text ? [message(text)] : []), ...tools.map((t, i) => fcall(t, i + 1))]);
}

// The event stream of the same Response. `split` cuts each arguments string into this many deltas.
// `completedTools` (when set) replaces the tools in response.completed's output: a differential fixture.
export function responsesStream({ text = "Let me check that.", tools = [], split = 3, completedTools = null, terminal = "response.completed" } = {}) {
  let n = 0;
  const ev = (d) => sse({ ...d, sequence_number: n++ });
  const out = [ev({ type: "response.created", response: base("in_progress", []) })];
  let idx = 0;
  if (text) {
    out.push(ev({ type: "response.output_item.added", output_index: idx, item: message(null, "in_progress") }));
    out.push(ev({ type: "response.output_text.delta", item_id: "msg_fake01", output_index: idx, content_index: 0, delta: text, logprobs: [] }));
    out.push(ev({ type: "response.output_item.done", output_index: idx, item: message(text) }));
    idx++;
  }
  tools.forEach((t, i) => {
    const args = JSON.stringify(t.input);
    const id = `fc_fake0${i + 1}`;
    out.push(ev({ type: "response.output_item.added", output_index: idx, item: fcall(t, i + 1, "", "in_progress") }));
    const step = Math.ceil(args.length / split);
    for (let j = 0; j < args.length; j += step) out.push(ev({ type: "response.function_call_arguments.delta", item_id: id, output_index: idx, delta: args.slice(j, j + step) }));
    out.push(ev({ type: "response.function_call_arguments.done", item_id: id, output_index: idx, arguments: args }));
    out.push(ev({ type: "response.output_item.done", output_index: idx, item: fcall(t, i + 1) }));
    idx++;
  });
  const final = completedTools || tools;
  if (terminal) out.push(ev({ type: terminal, response: base(terminal === "response.completed" ? "completed" : terminal === "response.incomplete" ? "incomplete" : "failed", [...(text ? [message(text)] : []), ...final.map((t, i) => fcall(t, i + 1))]) }));
  return out;
}

// A /v1/embeddings response: one vector per input.
export function embeddingsBody(count = 1) {
  return { object: "list", data: Array.from({ length: count }, (_, index) => ({ object: "embedding", index, embedding: [0.0023, -0.0093, 0.0157] })), model: "text-embedding-fake", usage: { prompt_tokens: 8, total_tokens: 8 } };
}
