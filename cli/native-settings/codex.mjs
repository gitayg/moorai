// OpenAI Codex admin requirements (requirements.toml) from the portable intent. Pure.
//
// Schema, quoted from learn.chatgpt.com/docs/enterprise/managed-configuration (read 2026-10-21; MoorAI's
// Codex adapter is verified against rust-v0.154.0):
//   location: "`/etc/codex/requirements.toml` on Unix systems, including Linux and macOS, or
//     `%ProgramData%\OpenAI\Codex\requirements.toml` on Windows".
//   allowed_web_search_modes: "`allowed_web_search_modes = []` allows only `"disabled"`."
//   allowed_permission_profiles: "When present, the table is the complete list of allowed profiles." "It
//     allows profiles set to `true` and denies profiles omitted or set to `false`" — example ":read-only".
//   mcp_servers: "[mcp_servers.docs] identity = { command = "codex-mcp" }"; "Stdio servers match on
//     `command`, and streamable HTTP servers match on `url`"; "If `mcp_servers` is present but empty, the
//     client disables all MCP servers." An identity is required, so a server name alone cannot be listed.
//   experimental_network: "`enabled = true` activates the managed proxy. Domain rules alone don't activate
//     it." "`*.example.com` matches subdomains only, while `**.example.com` also matches the apex domain."
//     "A matching deny rule wins over an allow rule." managed_allowed_domains_only = true keeps only the
//     managed allow rules. The section is marked experimental, and the docs do not say what happens to an
//     unlisted domain when managed_allowed_domains_only is false.
//   Requirements `[rules] prefix_rules` need at least one command token, so "every shell command" has no
//     form there; Codex has no per-tool deny for its shell, file-read or agent tools.
// The file is written whole: an existing requirements.toml with other requirements has to be merged by hand.

import { mapTools } from "./tools.mjs";
import { effectiveDeny } from "./intent.mjs";
import { domainPlan, domainStrings } from "./egress.mjs";
import { tomlKey, tomlValue, tomlTable } from "./toml.mjs";

const TAG = "codex";
const PATH = { darwin: "/etc/codex/requirements.toml", linux: "/etc/codex/requirements.toml", win32: "C:\\ProgramData\\OpenAI\\Codex\\requirements.toml" };
const WRITE_TOOLS = ["Edit", "MultiEdit", "Write"];
// The tools MoorAI's Codex adapter (cli/agent-hooks/codex.mjs) maps: shell -> Bash, apply_patch -> Write /
// MultiEdit, read -> Read, spawn_agent -> Task, web search. null = no deny form in requirements.toml.
const DENY = { Bash: null, Read: null, Task: null, Write: ["write"], Edit: ["write"], MultiEdit: ["write"], WebSearch: ["web_search"] };
const ASK = { Bash: null, Read: null, Task: null, Write: null, Edit: null, MultiEdit: null, WebSearch: null };
const HEADER = "# Generated by MoorAI (moorai-native-settings) from the organization's MoorAI policy.\n# A hand edit is reported as drift on the next check.\n";

export function codex(intent, { platform, mcpIdentities = {} }) {
  const unexpressed = [], notes = [{ reason: `${TAG}-whole-file` }];
  const t = mapTools(intent, TAG, { deny: DENY, ask: ASK });
  unexpressed.push(...t.unexpressed);
  const top = {}, tables = [];
  if (t.deny.includes("web_search")) top.allowed_web_search_modes = [];
  if (t.deny.includes("write")) {
    const denied = effectiveDeny(intent);
    const missing = WRITE_TOOLS.filter((w) => !denied.includes(w));
    if (missing.length) {
      for (const w of WRITE_TOOLS.filter((x) => !missing.includes(x))) unexpressed.push({ source: "tagActions", tool: w, effect: "omitted", reason: `${TAG}-write-needs-every-write-tool` });
    } else {
      // A read-only profile refuses every write the agent makes, shell writes included — MoorAI's write tag
      // also lands on shell commands parsed as writing, so the two are close but not the same.
      tables.push(tomlTable(["allowed_permission_profiles"], { ":read-only": true }));
      unexpressed.push({ source: "tagActions", item: "write", effect: "approximated", reason: `${TAG}-read-only-profile` });
    }
  }

  if (intent.mcp.allowOnly) {
    const known = intent.mcp.allowOnly.filter((s) => validIdentity(mcpIdentities[s]));
    if (!intent.mcp.allowOnly.length) tables.push(tomlTable(["mcp_servers"], {}));
    else if (!known.length) unexpressed.push({ source: "mcpAllow", effect: "coarsened", reason: `${TAG}-mcp-identity-required` });
    else {
      for (const s of known) tables.push(tomlTable(["mcp_servers", s], { identity: identityOf(mcpIdentities[s]) }));
      for (let k = known.length; k < intent.mcp.allowOnly.length; k++) unexpressed.push({ source: "mcpAllow", effect: "narrowed", reason: `${TAG}-mcp-identity-required` });
    }
  }

  const eg = intent.egress;
  if (eg.set) {
    const plan = domainPlan(eg, { ports: false, ip: "approximated", suffix: "exact" }, TAG);
    unexpressed.push(...plan.unexpressed);
    const domains = {};
    for (const a of plan.allows) for (const h of domainStrings(a)) domains[h] = "allow";
    for (const b of plan.blocks) for (const h of domainStrings(b)) domains[h] = "deny";
    tables.push(tomlTable(["experimental_network"], { enabled: true, managed_allowed_domains_only: eg.dflt === "block" }));
    const keys = Object.keys(domains).sort();
    if (keys.length) tables.push(`[experimental_network.domains]\n${keys.map((k) => `${tomlKey(k)} = ${tomlValue(domains[k])}\n`).join("")}`);
    if (eg.dflt !== "block") unexpressed.push({ source: "egressDefault", effect: "approximated", reason: `${TAG}-unlisted-domain-unstated` });
    notes.push({ reason: `${TAG}-network-experimental` });
  }

  const body = [Object.entries(top).map(([k, v]) => `${tomlKey(k)} = ${tomlValue(v)}\n`).join(""), ...tables].filter(Boolean);
  const files = body.length ? [{ path: PATH[platform], format: "toml", scope: "managed", merge: "whole", content: HEADER + "\n" + body.join("\n") }] : [];
  return { files, unexpressed, notes };
}

function validIdentity(x) {
  if (!x || typeof x !== "object") return false;
  const keys = Object.keys(x);
  return keys.length === 1 && ((keys[0] === "command" && typeof x.command === "string" && x.command) || (keys[0] === "url" && typeof x.url === "string" && /^https?:\/\//.test(x.url)));
}
const identityOf = (x) => (x.command ? { command: x.command } : { url: x.url });
