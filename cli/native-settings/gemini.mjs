// Gemini CLI admin-tier policy and system settings from the portable intent. Pure.
//
// Schema, quoted from geminicli.com/docs/reference (read 2026-10-21; the site notes Gemini CLI was replaced by
// Antigravity CLI for free users on 18 Jun 2026; MoorAI's Gemini adapter covers Gemini CLI):
//   policy-engine: admin policy directories "Linux: `/etc/gemini-cli/policies`", "macOS: `/Library/Application
//     Support/GeminiCli/policies`", "Windows: `C:\ProgramData\gemini-cli\policies`"; the admin tier is the
//     highest; "`final_priority = tier_base + (toml_priority / 1000)`" with TOML priority 0-999; rules are
//     `[[rule]]` with toolName, mcpName, commandPrefix, decision (allow, deny or ask_user) and priority;
//     `mcpName = "*"` "applies to all MCP servers". MoorAI never writes an allow rule there: in the policy
//     engine an allow skips the confirmation prompt.
//     "Do not use underscores (`_`) in your MCP server names."
//   configuration: system settings "Linux: `/etc/gemini-cli/settings.json`", "Windows:
//     `C:\ProgramData\gemini-cli\settings.json`", "macOS: `/Library/Application Support/GeminiCli/settings.json`"
//     (they override user and project settings); `mcp.allowed`: "A list of MCP servers to allow."
//   Gemini CLI has no domain allow/deny list (`tools.sandbox` is the "Legacy full-process sandbox"), so
//   egressRules have no Gemini form.

import { mapTools } from "./tools.mjs";
import { tomlArrayTable } from "./toml.mjs";

const TAG = "gemini";
const DIR = { darwin: "/Library/Application Support/GeminiCli", linux: "/etc/gemini-cli", win32: "C:\\ProgramData\\gemini-cli" };
const join = (platform, ...p) => [DIR[platform], ...p].join(platform === "win32" ? "\\" : "/");
// Tool names MoorAI's Gemini adapter maps (cli/agent-hooks/gemini.mjs). read_many_files is judged as Bash.
const MAP = { Bash: ["run_shell_command", "read_many_files"], Read: ["read_file"], Write: ["write_file"], Edit: ["replace"], WebFetch: ["web_fetch"], WebSearch: ["google_web_search"], Task: ["invoke_agent"] };
const HEADER = "# Generated by MoorAI (moorai-native-settings) from the organization's MoorAI policy.\n# A hand edit is reported as drift on the next check.\n";

export function gemini(intent, { platform }) {
  const unexpressed = [], files = [];
  const t = mapTools(intent, TAG, { deny: MAP, ask: MAP });
  unexpressed.push(...t.unexpressed);
  const rules = [
    ...t.deny.map((toolName) => tomlArrayTable("rule", { toolName, decision: "deny", priority: 900 })),
    ...t.ask.map((toolName) => tomlArrayTable("rule", { toolName, decision: "ask_user", priority: 800 }))
  ];
  if (intent.mcp.allowOnly) {
    if (!intent.mcp.allowOnly.length) rules.push(tomlArrayTable("rule", { mcpName: "*", decision: "deny", priority: 900 }));
    else {
      files.push({ path: join(platform, "settings.json"), format: "json", scope: "managed", merge: "keys", content: { mcp: { allowed: intent.mcp.allowOnly } } });
      if (intent.mcp.allowOnly.some((s) => s.includes("_"))) unexpressed.push({ source: "mcpAllow", effect: "approximated", reason: `${TAG}-server-name-underscore` });
    }
  }
  if (rules.length) files.unshift({ path: join(platform, "policies", "moorai.toml"), format: "toml", scope: "managed", merge: "whole", content: HEADER + "\n" + rules.join("\n") });
  const eg = intent.egress;
  for (const e of eg.entries) unexpressed.push({ source: "egressRules", index: e.index, ...(e.id ? { id: e.id } : {}), fields: ["host"], effect: "omitted", reason: `${TAG}-no-network-policy` });
  if (eg.dflt === "block") unexpressed.push({ source: "egressDefault", effect: "omitted", reason: `${TAG}-no-network-policy` });
  files.sort((a, b) => (a.path < b.path ? -1 : 1));
  return { files, unexpressed, notes: [] };
}
